-- Diagnostic
local diagnostic_goto = function(next, severity)
  local go = next and vim.diagnostic.goto_next or vim.diagnostic.goto_prev
  severity = severity and vim.diagnostic.severity[severity] or nil
  return function()
    go({ severity = severity })
  end
end
map("n", "<leader>cd", vim.diagnostic.open_float, { desc = "Line Diagnostics" })
map("n", "]d", diagnostic_goto(true), { desc = "Next Diagnostic" })
map("n", "[d", diagnostic_goto(false), { desc = "Prev Diagnostic" })
map("n", "]e", diagnostic_goto(true, "ERROR"), { desc = "Next Error" })
map("n", "[e", diagnostic_goto(false, "ERROR"), { desc = "Prev Error" })
map("n", "]w", diagnostic_goto(true, "WARN"), { desc = "Next Warning" })
map("n", "[w", diagnostic_goto(false, "WARN"), { desc = "Prev Warning" })

-- Toggle options (using snacks if available)
local function setup_toggle(key, option_name, option_config)
  local ok, snacks = pcall(require, "snacks")
  if ok then
    snacks.toggle.option(option_name, option_config or { name = option_name }):map(key)
  end
end

setup_toggle("<leader>us", "spell", { name = "Spelling" })
setup_toggle("<leader>uw", "wrap", { name = "Wrap" })
setup_toggle("<leader>uL", "relativenumber", { name = "Relative Number" })
setup_toggle("<leader>ul", "number", { name = "Line Number" })

